#!/usr/bin/env bash
# Koa variant of scripts/psi0/finetune_s06.sh: the same recipe, with Weights & Biases logging
# and Koa's scratch paths. The recipe is deliberately NOT edited -- not everyone runs on Koa,
# and its header documents a deliberate "no wandb".
#
# Instead this regenerates a wandb-enabled copy of the recipe on every run, from the pristine
# file, so the copy cannot drift from what it mirrors. The injection keys on one line; if that
# line ever moves, generation fails loudly rather than silently dropping the flags.
#
# Logging goes through the trainer's own path -- Psi0's scripts/train.py reads cfg.log.report_to and
# calls accelerator.init_trackers -- so nothing here reimplements wandb. The run name is the
# trainer's ($EXP + task + $TS). Offline is a fallback, not a failure: the run still trains and
# `wandb sync` uploads it afterwards.
#
# It also makes preemption survivable, which the recipe alone is not. See RESUME below.
#
#   PSI0_KOA_REPO=/path/to/fiatlux scripts/psi0/koa/finetune_koa.sh
#
# Reads $ROOT/.wandb_key (mode 600, not in the repo). Honours the recipe's own knobs: BATCH,
# ACCUM, STEPS, WARMUP, LR, CKPT_EVERY, EXP, TS.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
source "$HERE/env.sh"

WANDB_PROJECT_NAME="${WANDB_PROJECT_NAME:-fiatlux-psi0-s06}"
RECIPE="$REPO/scripts/psi0/finetune_s06.sh"
GEN="$ROOT/generated/finetune_s06_wandb.sh"
mkdir -p "$(dirname "$GEN")"

export OUT_DIR="$FT/runs"
export TS="${TS:-$(date +%y%m%d%H%M)}"

# Resume after a preemption. The recipe passes --train.resume_from_checkpoint=latest, but
# "latest" is not a keyword to this trainer: Trainer.resume_from_checkpoint() normpaths the
# value and looks for <value>/checkpoints, so it resolves to ./latest/checkpoints relative to
# $PSI0_REPO, never exists, and the run silently restarts from step 0. To actually resume, the
# real run directory has to be passed. It is $OUT_DIR/<train.name>/<exp><task>.<TS>, so with TS
# pinned at submit time the previous attempt is findable by glob -- which is why a requeued job
# must carry the same TS (sbatch --export=ALL does that by default).
RESUME=""
for d in "$OUT_DIR/finetune"/*."$TS"; do
    [ -d "$d/checkpoints" ] || continue
    compgen -G "$d/checkpoints/ckpt_*" > /dev/null || continue
    RESUME="$d"
done
if [ -n "$RESUME" ]; then
    echo "[koa] resuming $RESUME from $(ls "$RESUME/checkpoints" | tr '\n' ' ')"
else
    echo "[koa] fresh run (no checkpoint under $OUT_DIR/finetune/*.$TS)"
fi

# A fixed wandb id keeps a requeued attempt on the same wandb run instead of opening a new one
# each time. resume=allow creates it on the first attempt and resumes it after that.
WANDB_RUN_ID="${WANDB_RUN_ID:-s06ft-$TS}"

python3 - "$RECIPE" "$GEN" "$WANDB_PROJECT_NAME" "$RESUME" "$WANDB_RUN_ID" <<'PYEOF'
import pathlib
import sys

recipe, gen, project, resume, run_id = sys.argv[1:6]
text = pathlib.Path(recipe).read_text()

# Point the recipe's resume flag at the real run directory (see RESUME in finetune_koa.sh).
stock_resume = "--train.resume_from_checkpoint=latest"
if text.count(stock_resume) != 1:
    sys.exit(
        f"FATAL: '{stock_resume}' found {text.count(stock_resume)}x in {recipe} (expected 1).\n"
        "The recipe's resume flag moved; update scripts/psi0/koa/finetune_koa.sh to match."
    )
if resume:
    text = text.replace(stock_resume, f"--train.resume_from_checkpoint={resume}")

# The line that closes the recipe's argument array and starts its tail.
anchor = 'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"'
if text.count(anchor) != 1:
    sys.exit(
        f"FATAL: anchor found {text.count(anchor)}x in {recipe} (expected 1).\n"
        "finetune_s06.sh changed shape; update scripts/psi0/koa/finetune_koa.sh to match."
    )

scripts_dir = str(pathlib.Path(recipe).parent)
injected = (
    "# --- generated by scripts/psi0/koa/finetune_koa.sh; edit that, not this ---\n"
    "args+=( --log.report_to=wandb"
    f" --wandb.project={project} --wandb.id={run_id} --wandb.resume=allow )\n"
    f"{anchor}\n"
    f'HERE="{scripts_dir}"   # this copy lives outside the repo; helpers do not\n'
    "# --- end generated ---"
)
pathlib.Path(gen).write_text(text.replace(anchor, injected))
print(f"[koa] generated {gen} (wandb project {project})")
PYEOF

bash -n "$GEN"
grep -q -- "--log.report_to=wandb" "$GEN" || { echo "FATAL: flags missing from $GEN" >&2; exit 1; }

# wandb credentials and scratch-local state.
[ -s "$ROOT/.wandb_key" ] || { echo "FATAL: no $ROOT/.wandb_key (mode 600)" >&2; exit 1; }
WANDB_API_KEY="$(cat "$ROOT/.wandb_key")"
export WANDB_API_KEY
export WANDB_DIR="$ROOT/wandb" WANDB_CACHE_DIR="$ROOT/wandb/cache" WANDB_CONFIG_DIR="$ROOT/wandb/config"
mkdir -p "$WANDB_DIR" "$WANDB_CACHE_DIR" "$WANDB_CONFIG_DIR"
# Reachability, not health: api.wandb.ai answers 404 on / and 405 on /graphql for a GET, so
# `curl -f` (and -I) call a perfectly reachable host a failure. Any HTTP code means the host
# answered; curl writes 000 only when the connection itself failed.
if [ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 15 https://api.wandb.ai 2>/dev/null)" != "000" ]; then
    export WANDB_MODE=online
else
    export WANDB_MODE=offline
    echo "[koa] WARNING: api.wandb.ai unreachable from $(hostname); logging offline."
    echo "[koa]          upload later: $PSI0_REPO/.venv-psi/bin/wandb sync $WANDB_DIR/offline-run-*"
fi
echo "[koa] WANDB_MODE=$WANDB_MODE"

export PSI0_REPO
export PACK_ROOT="$FT/packs"
export PACK_ID="${PACK_ID:-s06_dispose_teleop}"
export INIT_DIR="$FT/init/psi_dream_40k"
echo "[koa] run dir: $OUT_DIR/finetune/${EXP:-s06ft}*.$TS  (wandb id $WANDB_RUN_ID)"

exec bash "$GEN"
